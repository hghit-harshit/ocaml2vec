#!/usr/bin/env bash
# gen_build_id.sh <ocamlopt>: the MD5 of the compiler this extractor is built
# with; dumps must carry the same build hash (D5.13).
set -euo pipefail
printf '(* generated by gen_build_id.sh: MD5 of %s (D5.13) *)\n' "$(basename "$1")"
printf 'let ocamlopt_md5 = "%s"\n' "$(md5sum "$(readlink -f "$1")" | cut -d' ' -f1)"
